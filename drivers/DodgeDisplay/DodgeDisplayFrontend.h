#pragma once
#include <IOKit/IOService.h>
#include <IOKit/IOMemoryDescriptor.h>
#include "DodgeDisplayTransfer.h"

struct IOMFBSwapIORequest;
struct DodgeDisplayFrontend;
enum class DodgeDisplayProducer { CpuOnly, AdrenoTimeline };

// Construct after the exact framebuffer's startup queues and GOP-matching mode
// are established, before registerService/client use. The caller owns all input
// objects and serializes this unpublished service's start/stop. When outside
// the work-loop gate, the factory retains its inputs, enters runAction and
// rechecks the loop/gate, mode and startup queues before creating anything.
// CpuCopy permits a null presenter. This does not publish a service.
DodgeDisplayFrontend *dodge_display_frontend_create(IOService *,IOService *presenter,IOMemoryMap *scanout,
    DodgeDisplayProducer producer=DodgeDisplayProducer::AdrenoTimeline,
    DodgeDisplayTransfer transfer=DodgeDisplayTransfer::CpuCopy);
// Adapter for original slot 178. Copies a canonical default layer-0 packet,
// enters the original work-loop gate, reserves an ID, and invokes the real
// original packet builder. An unrecognized packet returns Unsupported.
// Adreno mode captures the first valid submitted fence once per request,
// then waits on a gated timer without treating a query failure as completion.
IOReturn dodge_display_frontend_submit(DodgeDisplayFrontend *,const void *packet,unsigned bytes,void *submitter);
// Adapters for exact original slots 282 and 276, called on the same gate.
// Validation binds only a request generated by the guarded packet call.
bool dodge_display_frontend_validate(DodgeDisplayFrontend *,IOMFBSwapIORequest *);
IOReturn dodge_display_frontend_kick(DodgeDisplayFrontend *);
// Optional logical 60 Hz notifications, disabled initially. This uses the
// original sender on the same work loop; it does not announce panel vblank.
IOReturn dodge_display_frontend_set_refresh(DodgeDisplayFrontend *,bool enabled);
// Stop marks the controller as draining. Busy retains its owner reference:
// the caller must quiesce/stop its presenter, allow the pending callback to
// drain, then retry. Success consumes the owner reference. All calls gated.
// Failed GPU work must be quiescent before the bridge's CPU fallback callback.
IOReturn dodge_display_frontend_stop(DodgeDisplayFrontend *);

struct DodgeDisplayFrontendStatus {
    uint64_t submitted,validated,retired;
    uint32_t pending;
    IOReturn last;
    bool active,draining,producerWaiting;
};
bool dodge_display_frontend_status(DodgeDisplayFrontend *,DodgeDisplayFrontendStatus *);
